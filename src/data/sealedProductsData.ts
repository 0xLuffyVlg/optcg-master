export function getSealedProductById(id: string): SealedProductWithImages | undefined {
  if (!id) return undefined;
  const cleanId = id.toLowerCase().replace(/[^a-z0-9]/g, '');
  return allSealedProducts.find(p => {
    const pCleanId = p.id.toLowerCase().replace(/[^a-z0-9]/g, '');
    const pCode = p.code ? p.code.toLowerCase().replace(/[^a-z0-9]/g, '') : '';
    return p.id.toLowerCase() === id.toLowerCase() ||
           pCleanId === cleanId ||
           (pCode && cleanId.includes(pCode) && (cleanId.includes(p.category) || pCode === cleanId));
  });
}

export function getProductPriceForLanguage(product: SealedProduct, language?: SealedLanguage): number {
  if (language === 'JP') {
    return product.estimatedMarketJapEur ?? (product.estimatedMarketEur * 0.55);
  }
  if (language === 'FR') {
    return product.estimatedMarketFrEur ?? product.estimatedMarketEur;
  }
  return product.estimatedMarketEur;
}

export function getCardtraderUrl(product?: SealedProduct | SealedProductWithImages | null, language?: SealedLanguage): string {
  if (!product) return 'https://www.cardtrader.com/en/games/one-piece';
  
  const p = product as SealedProductWithImages;
  if (language === 'JP' && p.cardtraderJapUrl) {
    return p.cardtraderJapUrl;
  }
  if (product.cardtraderUrl) {
    return product.cardtraderUrl;
  }
  
  const code = product.code || '';
  const cat = product.category || '';
  let term = '';
  if (cat === 'display') term = `${code} Booster Box`;
  else if (cat === 'booster') term = `${code} Booster Pack`;
  else if (cat === 'starter_deck') term = `${code} Starter Deck`;
  else term = p.englishName || product.name || code;
  
  if (language === 'JP') term += ' Japanese';
  return `https://www.cardtrader.com/en/search?q=${encodeURIComponent(term.trim())}`;
}

export function getCardmarketUrl(product?: SealedProduct | SealedProductWithImages | null, language?: SealedLanguage): string {
  if (!product) return 'https://www.cardmarket.com/en/OnePiece';
  if (product.cardmarketUrl) return product.cardmarketUrl;
  const code = product.code || '';
  const term = `${code} ${(product as any).englishName || product.name || ''}`;
  return `https://www.cardmarket.com/en/OnePiece/Products/Search?searchString=${encodeURIComponent(term.trim())}`;
}

