const allRules = buildEngine();

/**
 * Translates an effect or trigger text from English to French using official Bandai OPTCG wording.
 */
export function translateCardEffect(text: string, lang: AppLanguage = getDeviceLanguage()): string {
  if (!text || lang === 'EN') return text;

  let res = text;
  for (const [regex, replacement] of allRules) {
    if (typeof replacement === 'function') {
      res = res.replace(regex, replacement as any);
    } else {
      res = res.replace(regex, replacement);
    }
  }

  return res;
}

/**
 * Translates Category into user language
 */
export function translateCategory(cat: string, lang: AppLanguage = getDeviceLanguage()): string {
  if (lang === 'EN') return cat;
  switch (cat) {
    case 'Leader': return 'Leader';
    case 'Character': return 'Personnage';
    case 'Event': return 'Événement';
    case 'Stage': return 'Terrain';
    default: return cat;
  }
}

/**
 * Translates Attribute into user language
 */
