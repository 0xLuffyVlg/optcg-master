/**
 * Detects the user's system / browser language
 * If device is set to English (e.g. in UK, US), returns 'EN'
 * If device is set to French (e.g. in France, Belgium, Canada), returns 'FR'
 */
export function getDeviceLanguage(): AppLanguage {
  try {
    const saved = localStorage.getItem(LANG_STORAGE_KEY);
    if (saved === 'FR' || saved === 'EN') {
      return saved;
    }

    if (typeof navigator !== 'undefined') {
      const browserLang = (navigator.language || (navigator as any).userLanguage || '').toLowerCase();
      if (browserLang.startsWith('en')) {
        return 'EN';
      }
      if (browserLang.startsWith('fr')) {
        return 'FR';
      }
    }
  } catch (e) {}

  return 'FR';
}

export function setDeviceLanguage(lang: AppLanguage): void {
  try {
    localStorage.setItem(LANG_STORAGE_KEY, lang);
    window.dispatchEvent(new CustomEvent('optcg-language-changed', { detail: lang }));
  } catch (e) {}
}

