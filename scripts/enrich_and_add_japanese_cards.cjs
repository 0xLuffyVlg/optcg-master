let addedCount = 0;
const existingCodes = new Set(cards.map(c => (c.card_code || '').toUpperCase()));

for (const newCard of NEW_JAPANESE_CARDS) {
  if (!existingCodes.has(newCard.card_code.toUpperCase())) {
    cards.push(newCard);
    existingCodes.add(newCard.card_code.toUpperCase());
    addedCount++;
  } else {
    // If it exists, ensure it has japanese props
    const existing = cards.find(c => (c.card_code || '').toUpperCase() === newCard.card_code.toUpperCase());
    if (existing) {
      existing.jp_name = newCard.jp_name;
      existing.is_japanese = true;
      if (newCard.effect_fr && !existing.effect_fr) existing.effect_fr = newCard.effect_fr;
    }
  }
}

fs.writeFileSync(cardsPath, JSON.stringify(cards, null, 2), 'utf8');
console.log('Successfully added ' + addedCount + ' new Japanese cards! Total cards now: ' + cards.length);
