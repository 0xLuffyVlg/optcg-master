// 1. Enrich existing cards with Japanese names
let enrichedCount = 0;
for (const card of cards) {
  const nameLow = (card.name || '').toLowerCase().trim();
  for (const [key, jp] of Object.entries(JP_CHAR_MAP)) {
    if (nameLow === key || nameLow.includes(key)) {
      card.jp_name = jp;
      enrichedCount++;
      break;
    }
  }
}
